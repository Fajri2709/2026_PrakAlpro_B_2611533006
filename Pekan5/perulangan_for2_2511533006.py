ulang_3006 = int(input("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_3006-1)
for i_3006 in range(ulang_3006):
    print(i_3006, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_3006)
for i_3006 in range(1,ulang_3006+1):
    print(i_3006, end=" ")